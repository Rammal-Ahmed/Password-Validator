print("PASSWORD VALIDATOR".center(30))
print("=" * 30)

letter = False
num = False
sign = False

passw = input("Enter a Password: \n")

for pv in passw:
    if pv.isalpha():
        letter = True

    if pv in "0123456789":
        num = True

    if pv == "@":
        sign = True

print()

if len(passw) < 8:
    print("Password must be at least 8 characters long")
elif not letter:
    print("Please include letters in your password")
elif num and sign:
    print("Password Accepted")
elif not num and not sign:
    print("Please add number and an @ sign to your password")
elif not num:
    print("Please add a number to your password")
else:
    print("Please add an @ sign to your password")

